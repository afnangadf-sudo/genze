// Tiny i18n dictionary. All user-facing copy lives here — plain language,
// no technical words, in English, natural Urdu, Arabic, Turkish and Persian.
//
// To add a 6th language: add a `Strings` dictionary below (copy any one and
// translate every key) and add one line to LANGS. Nothing else changes.

import type { SupportedLanguage } from "@genze/shared";

export type Lang = SupportedLanguage;

export interface LangInfo {
  code: Lang;
  /** Native name, shown in the picker. */
  nativeName: string;
  rtl: boolean;
}

/** Language registry — the single place a new language is registered. */
export const LANGS: LangInfo[] = [
  { code: "en", nativeName: "English", rtl: false },
  { code: "ur", nativeName: "اردو", rtl: true },
  { code: "ar", nativeName: "العربية", rtl: true },
  { code: "tr", nativeName: "Türkçe", rtl: false },
  { code: "fa", nativeName: "فارسی", rtl: true },
];

export function isLang(v: unknown): v is Lang {
  return LANGS.some((l) => l.code === v);
}

/** Reading direction for a language. Pure — used by tests too. */
export function langDir(lang: Lang): "rtl" | "ltr" {
  return LANGS.find((l) => l.code === lang)?.rtl ? "rtl" : "ltr";
}

